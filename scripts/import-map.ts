/**
 * Reads the terrain drawing and writes supabase/seed/03_map.sql with the map
 * position of every plot and facility and every plot-facility distance.
 *
 *   npm run import-map
 *
 * The seed runs on every `docker compose up` (the migrate service), so the
 * database follows the drawing. Distances are never entered by hand.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { importMap } from "../src/lib/map/geometry";

const svg = readFileSync("src/content/map/terrain.svg", "utf8");
const { plots, facilities, distances } = importMap(svg);

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

const lines = [
  "-- Generated by scripts/import-map.ts from src/content/map/terrain.svg.",
  "-- Do not edit: change the drawing and run `npm run import-map`.",
  "",
  ...plots.map((p) => `update public.plots set map_x = ${p.cx}, map_y = ${p.cy} where id = ${q(p.id)};`),
  ...facilities.map(
    (f) => `update public.facilities set map_x = ${f.cx}, map_y = ${f.cy} where id = ${q(f.id)};`,
  ),
  "",
  "insert into public.plot_distances (plot_id, facility_id, metres)",
  "select v.plot_id, v.facility_id, v.metres",
  "from (values",
  distances.map((d) => `  (${q(d.plotId)}, ${q(d.facilityId)}, ${d.metres})`).join(",\n"),
  ") as v (plot_id, facility_id, metres)",
  "join public.plots p on p.id = v.plot_id",
  "join public.facilities f on f.id = v.facility_id",
  "on conflict (plot_id, facility_id) do update set metres = excluded.metres;",
  "",
];

writeFileSync("supabase/seed/03_map.sql", lines.join("\n"));
console.log(`Wrote ${plots.length} plots, ${facilities.length} facilities, ${distances.length} distances.`);
