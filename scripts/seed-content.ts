/**
 * Writes supabase/seed/02_content.sql from the typed content in src/content.
 *
 *   npm run seed-content
 *
 * The content files stay the starting point for a fresh database. Rows that
 * exist are never overwritten, so what Bert changes in the admin panel stays.
 */
import { writeFileSync } from "node:fs";
import { facilities } from "../src/content/facilities";
import { insert, localized, type Row } from "./lib/sql";
import { contentSeed } from "./seed-content-more";

const facilityRows: Row[] = facilities.map((f, i) => ({
  id: f.id,
  icon: f.icon,
  surface: f.surface,
  on_home: f.onHome,
  hours_label: f.hoursLabel,
  sort: i + 1,
  ...localized(f, ["name", "summary", "description", "hours", "access", "location"]),
}));

const sql = [
  "-- Generated by scripts/seed-content.ts from src/content. Do not edit:",
  "-- change the content files and run `npm run seed-content`.",
  "",
  insert("facilities", facilityRows, "id"),
  ...contentSeed(),
].join("\n");

writeFileSync("supabase/seed/02_content.sql", sql);
console.log("Wrote supabase/seed/02_content.sql");
